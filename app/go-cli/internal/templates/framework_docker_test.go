func TestJavaScriptFrameworkDockerfilesUseBunAndPreserveCaching(t *testing.T) {
	for _, framework := range []string{"hono", "fastify", "nextjs", "tanstack-start"} {
		prod, _, _ := FrameworkDockerfiles(framework)
		lockfiles := strings.Index(prod, "COPY package.json bun.lock ./")
		source := strings.Index(prod, "COPY . .")
		if lockfiles < 0 || source < 0 || lockfiles > source {
			t.Fatalf("%s must copy package manifests before application source", framework)
		}
		if !strings.Contains(prod, "bun install --frozen-lockfile") {
			t.Fatalf("%s must build through a frozen Bun install", framework)
		}
		if framework == "hono" && (!strings.Contains(prod, "[ -f src/index.ts ]") || !strings.Contains(prod, "[ -f index.ts ]")) {
			t.Fatal("hono must support both the stock src/index.ts and root index.ts Bun entrypoints")
		}
		if framework == "fastify" && !strings.Contains(prod, "bun build server.ts --target node --format esm --outfile dist/server.js") {
			t.Fatal("fastify must build the generated Bun server without package scripts")
		}
		if framework == "nextjs" && !strings.Contains(prod, "node node_modules/next/dist/bin/next build") {
			t.Fatal("nextjs must run its current build binary directly rather than through Bun's incompatible Node shim")
		}
		if framework == "tanstack-start" && !strings.Contains(prod, "bun node_modules/vite/bin/vite.js build") {
			t.Fatal("tanstack-start must run the Vite binary directly without npm/npx")
		}
		if strings.Contains(prod, "npm ") || strings.Contains(prod, "npx ") {
			t.Fatalf("%s must not use npm or npx", framework)
		}
		if !strings.Contains(prod, "--mount=type=cache") {
			t.Fatalf("%s must use a BuildKit package-cache mount", framework)
		}
	}
}

func TestFastAPIDockerfileUsesLockedDependenciesBeforeSource(t *testing.T) {
	prod, _, ok := FrameworkDockerfiles("fastapi")
	if !ok {
		t.Fatal("fastapi must have a production template")
	}
	lockfiles := strings.Index(prod, "COPY pyproject.toml uv.lock ./")
	source := strings.Index(prod, "COPY . .")
	if lockfiles < 0 || source < 0 || lockfiles > source {
		t.Fatal("fastapi must copy its lockfiles before application source")
	}
	if !strings.Contains(prod, "uv sync --frozen --no-dev") {
		t.Fatal("fastapi must install frozen production dependencies")
	}
	if !strings.Contains(prod, frameworkUVImage) || !strings.Contains(prod, frameworkPythonImage) {
		t.Fatal("fastapi must match the Python 3.11 version generated by uv init")
	}
	if !strings.Contains(prod, "--mount=type=cache,target=/root/.cache/uv") {
		t.Fatal("fastapi must use a BuildKit uv cache mount")
	}
}

func TestProductionTemplatesKeepBuildToolsAndDevDependenciesOutOfRuntime(t *testing.T) {
	for _, framework := range []string{"hono", "fastify", "nextjs", "tanstack-start", "fastapi"} {
		prod, _, _ := FrameworkDockerfiles(framework)
		runtime := prod[strings.LastIndex(prod, "FROM "):]
		if strings.Contains(runtime, "RUN bun install") || strings.Contains(runtime, "RUN bun run build") || strings.Contains(runtime, "uv sync") {
			t.Fatalf("%s runtime stage must not install or build dependencies", framework)
		}
		if framework == "hono" || framework == "fastify" {
			if strings.Contains(runtime, "node_modules") || !strings.Contains(prod, "--outfile dist/") {
				t.Fatalf("%s must ship only its compiled server, without dependency directories", framework)
			}
			if !strings.Contains(runtime, frameworkNodeImage) || strings.Contains(runtime, "CMD [\"bun\"") {
				t.Fatalf("%s production runtime must use portable Node rather than Bun's AVX2 runtime", framework)
			}
		}
		if framework == "fastapi" && !strings.Contains(prod, "uv sync --frozen --no-dev") {
			t.Fatal("fastapi must install only locked production dependencies")
		}
	}
}

