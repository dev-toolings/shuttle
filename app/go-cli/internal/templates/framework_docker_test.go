func TestFrameworkDockerignore(t *testing.T) {
	for _, framework := range []string{"hono", "fastify", "nextjs", "tanstack-start", "fastapi"} {
		ignore, ok := FrameworkDockerignore(framework)
		if !ok || !strings.Contains(ignore, ".git") {
			t.Fatalf("%s must have a Docker ignore template", framework)
		}
	}
	if _, ok := FrameworkDockerignore("rails"); ok {
		t.Fatal("unknown frameworks must not return a Docker ignore template")
	}
	fastAPI, _ := FrameworkDockerignore("fastapi")
	if strings.Contains(fastAPI, "README.md") {
		t.Fatal("fastapi Docker ignore must retain the README required by its pyproject build metadata")
	}
}
