func TestFrameworkDockerfilesExposeRequestedTemplates(t *testing.T) {
	frameworks := []struct {
		name   string
		hasDev bool
	}{
		{name: "hono", hasDev: true},
		{name: "fastify", hasDev: true},
		{name: "nextjs"},
		{name: "tanstack-start"},
		{name: "fastapi", hasDev: true},
	}

	for _, framework := range frameworks {
		prod, dev, ok := FrameworkDockerfiles(framework.name)
		if !ok || prod == "" {
			t.Fatalf("%s must have a production template", framework.name)
		}
		if (dev != "") != framework.hasDev {
			t.Fatalf("%s development template presence = %t, want %t", framework.name, dev != "", framework.hasDev)
		}
		if !strings.Contains(prod, "USER ") || !strings.Contains(prod, "HEALTHCHECK ") {
			t.Fatalf("%s production template must have an unprivileged user and healthcheck", framework.name)
		}
	}

	if _, _, ok := FrameworkDockerfiles("rails"); ok {
		t.Fatal("unknown frameworks must not return a template")
	}
	if prod, _, ok := FrameworkDockerfiles("tanstack_start"); !ok || prod == "" {
		t.Fatal("tanstack_start compatibility alias must resolve")
	}
}

