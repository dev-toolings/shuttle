func TestDevelopmentTemplatesAreFrozenAndNonRoot(t *testing.T) {
	for _, framework := range []string{"hono", "fastify", "fastapi"} {
		_, dev, _ := FrameworkDockerfiles(framework)
		if !strings.Contains(dev, "--frozen-lockfile") && !strings.Contains(dev, "uv sync --frozen") {
			t.Fatalf("%s dev template must use its lockfile", framework)
		}
		if !strings.Contains(dev, "USER bun") && !strings.Contains(dev, "USER app") {
			t.Fatalf("%s dev template must run as a non-root user", framework)
		}
		if !strings.Contains(dev, "HEALTHCHECK ") {
			t.Fatalf("%s dev template must have a healthcheck", framework)
		}
		if (framework == "hono" || framework == "fastify") && !strings.Contains(dev, "RUN chown bun:bun /app") {
			t.Fatalf("%s dev template must make its workdir writable before switching to bun", framework)
		}
		if framework == "fastapi" && !strings.Contains(dev, "UV_CACHE_DIR=/tmp/uv-cache") {
			t.Fatal("fastapi dev template must use a cache path writable by the non-root app user")
		}
	}
}

