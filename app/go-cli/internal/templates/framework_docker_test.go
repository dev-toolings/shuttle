func TestNextJSDockerfileBuildsAStandaloneRuntimeClosure(t *testing.T) {
	prod, _, ok := FrameworkDockerfiles("nextjs")
	if !ok {
		t.Fatal("nextjs must have a production template")
	}
	if !strings.Contains(prod, "ENV NEXT_PRIVATE_STANDALONE=1") {
		t.Fatal("nextjs must enable standalone output without requiring a user config edit")
	}
	for _, want := range []string{
		"/app/.next/standalone ./",
		"cp -a .next/static .next/standalone/.next/static",
		"ENV HOSTNAME=0.0.0.0",
		`CMD ["node", "server.js"]`,
		frameworkNodeImage,
	} {
		if !strings.Contains(prod, want) {
			t.Fatalf("nextjs standalone runtime missing %q", want)
		}
	}
	runtime := prod[strings.LastIndex(prod, " AS runtime"):]
	if strings.Contains(runtime, "node_modules") || strings.Contains(runtime, ".next ./.next") {
		t.Fatal("nextjs runtime must contain only the traced standalone closure")
	}
}

func TestTanStackDockerfileSupportsCurrentAndLegacyRuntimeClosures(t *testing.T) {
	prod, _, ok := FrameworkDockerfiles("tanstack-start")
	if !ok || !strings.Contains(prod, "[ -f .output/server/index.mjs ]") || !strings.Contains(prod, "cp -a .output /runtime/.output") {
		t.Fatal("tanstack-start must copy the current stock Nitro runtime closure")
	}
	if !strings.Contains(prod, "[ -f dist/server/server.js ]") || !strings.Contains(prod, "cp -a dist /runtime/") || !strings.Contains(prod, "import application from './dist/server/server.js'") {
		t.Fatal("tanstack-start must retain the legacy fetch-output adapter")
	}
	if !strings.Contains(prod, "bun install --frozen-lockfile --production") || !strings.Contains(prod, "COPY --from=builder --chown=tanstack:tanstack /runtime ./") {
		t.Fatal("tanstack-start must retain production dependencies only for legacy output")
	}
	if !strings.Contains(prod, "appResponse.headers.getSetCookie()") || !strings.Contains(prod, "headers['set-cookie'] = cookies") {
		t.Fatal("tanstack-start adapter must preserve repeated Set-Cookie headers")
	}
	if !strings.Contains(prod, "} catch (error) {") || !strings.Contains(prod, "response.end('Internal Server Error')") {
		t.Fatal("tanstack-start adapter must convert rejected handlers into an HTTP 500")
	}
	if !strings.Contains(prod, "stream.on('error', (error) => {") || !strings.Contains(prod, "response.destroy()") {
		t.Fatal("tanstack-start adapter must contain asynchronous response stream failures")
	}
}

