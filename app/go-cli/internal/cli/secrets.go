const maxSecretBytes = 1024 * 1024

// defaultSecretStorePath is where the encrypted local store lives unless the
// configuration says otherwise.
const defaultSecretStorePath = ".shuttle/secrets.enc"

// defaultPassphrasePath is where Shuttle looks for the store passphrase when
// nothing else supplies it.
//
// It exists because the only previous source was an environment variable, so
// every non-interactive deploy — a Makefile target, a CI job — had to invent its
// own storage for the key that protects every application secret, and none of
// those inventions were documented anywhere. A per-application file under the
// user's config directory is one answer Shuttle can name in an error message.
//
// Empty when the application is unknown: guessing a filename would read a
// passphrase meant for another stack.
//
// An explicit XDG_CONFIG_HOME wins on every platform. os.UserConfigDir honours
// it only on Linux; on macOS it answers ~/Library/Application Support whatever
// the environment says, so a CI job or a Makefile that set the variable to
// point Shuttle at a file would be silently ignored on one operating system
// and obeyed on the other. A path the operator named is the path that is read.
func defaultPassphrasePath(app string) string {
	if strings.TrimSpace(app) == "" {
		return ""
	}
	root := strings.TrimSpace(os.Getenv("XDG_CONFIG_HOME"))
	if root == "" || !filepath.IsAbs(root) {
		var err error
		if root, err = os.UserConfigDir(); err != nil {
			return ""
		}
	}
	return filepath.Join(root, "shuttle", app+".passphrase")
}

// readPassphraseFile reads a passphrase from disk, refusing a file anyone else
// on the machine can read.
//
// One trailing newline is dropped, and only one: the file is normally written
// by a shell, and `$(cat file)` — what operators do today — drops it too, so a
// stored passphrase keeps working through either path. Nothing else is trimmed,
// because a passphrase may legitimately end in a space.
func readPassphraseFile(path string) (string, error) {
	info, err := os.Stat(path)
	if err != nil {
		return "", err
	}
	if info.Mode().Perm()&0o077 != 0 {
		return "", fmt.Errorf("passphrase file %s is mode %#o; it must not be readable by group or other (chmod 600)", path, info.Mode().Perm())
	}
	body, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	value := strings.TrimSuffix(strings.TrimSuffix(string(body), "\n"), "\r")
	if value == "" {
		return "", fmt.Errorf("passphrase file %s is empty", path)
	}
	return value, nil
}

// openSecretStore opens the encrypted local store. The passphrase is never read
// from the configuration and never written anywhere; it comes from, in order,
// the environment, a file the environment names, the application's default
// passphrase file, and finally the terminal when there is one.
//
// The environment variable stays first so an existing deploy keeps resolving
// exactly what it resolved before.
func openSecretStore(path, app string) (secrets.Store, error) {
	passphrase := os.Getenv("SHUTTLE_SECRETS_PASSPHRASE")
	if passphrase == "" {
		if named := strings.TrimSpace(os.Getenv("SHUTTLE_SECRETS_PASSPHRASE_FILE")); named != "" {
			// Named explicitly, so a missing or unreadable file is an error
			// rather than a reason to fall through to a prompt that would hang
			// a Makefile or a CI job.
			value, err := readPassphraseFile(named)
			if err != nil {
				return secrets.Store{}, err
			}
			passphrase = value
		}
	}
	if passphrase == "" {
		if fallback := defaultPassphrasePath(app); fallback != "" {
			value, err := readPassphraseFile(fallback)
			if err == nil {
				passphrase = value
			} else if !os.IsNotExist(err) {
				return secrets.Store{}, err
			}
		}
	}
	if passphrase == "" && term.IsTerminal(int(os.Stdin.Fd())) {
		fmt.Fprint(os.Stderr, "Secrets passphrase: ")
		raw, err := term.ReadPassword(int(os.Stdin.Fd()))
		fmt.Fprintln(os.Stderr)
		if err != nil {
			return secrets.Store{}, err
		}
		passphrase = string(raw)
	}
	return secrets.Store{Path: path, Passphrase: passphrase}, nil
}

// applicationSecretStore is the store a deploy reads declared secrets from.
func applicationSecretStore(cfg *config.Config) (secrets.Store, error) {
	path := strings.TrimSpace(cfg.Secrets.File)
	if path == "" {
		path = defaultSecretStorePath
	}
	return openSecretStore(path, cfg.App)
}

// newSecretsCommand deliberately manages only the encrypted local store.
// Infrastructure credentials are generated by the root helper on the VPS;
// the unprivileged deploy account never receives Docker socket access.
func newSecretsCommand() *cobra.Command {
	var path string
	root := &cobra.Command{
		Use:   "secrets",
		Short: "Manage the encrypted local secret store",
		Args:  cobra.NoArgs,
	}
	root.PersistentFlags().StringVar(&path, "file", "", "encrypted secret store (default: secrets.file, else "+defaultSecretStorePath+")")
	root.AddCommand(newHashvaultSyncCommand())

	// Best effort: the store is per project, so a config.json in the working
	// directory names the application whose passphrase file to look for. Its
	// absence is not an error here — `shuttle secrets` still works from the
	// environment or a terminal.
	app := ""
	configuredPath := ""
	hostEnvFile := ""
	hashvaultBackend := false
	if cfg, err := loadWithFlags(configFlags{}); err == nil {
		app = cfg.App
		configuredPath = strings.TrimSpace(cfg.Secrets.File)
		if cfg.UsesHostSecrets() {
			hostEnvFile = cfg.Secrets.Host.EnvFile
		}
		hashvaultBackend = cfg.UsesHashvaultSecrets()
	}
	openStore := func() (secrets.Store, error) {
		if hashvaultBackend && strings.TrimSpace(path) == "" {
			return secrets.Store{}, fmt.Errorf("this project uses hashvault; manage values with its CLI or UI, or use shuttle secrets sync to retry release confirmation")
		}
		// The flag used to default to the literal store path, which meant a
		// project that moved its store with secrets.file was read at the
		// declared path by every deploy and at the default path by every
		// `shuttle secrets` — so `list` showed an empty store for secrets that
		// were there, and `set` wrote a second one the deploy never read.
		resolved := strings.TrimSpace(path)
		if resolved == "" {
			resolved = configuredPath
		}
		if resolved == "" {
			resolved = defaultSecretStorePath
		}
		if hostEnvFile != "" && strings.TrimSpace(path) == "" {
			// Silence here would be the wrong answer twice over: an empty
			// listing for an application whose secrets exist, and a `set` that
			// writes a store no deploy of this project will ever open.
			return secrets.Store{}, fmt.Errorf("this project declares secrets.backend: %s, so its secrets live in %s on the VPS and are never held on this machine; edit them there, or pass --file to work on a local store anyway", config.SecretsBackendHost, hostEnvFile)
		}
		return openSecretStore(resolved, app)
	}

	var fromStdin bool
	var fromFile string
	set := &cobra.Command{
		Use:   "set <key>",
		Short: "Store a secret locally",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if !config.ValidSecretKey(args[0]) {
				return fmt.Errorf("invalid secret key %q: expected [A-Z_][A-Z0-9_]*", args[0])
			}
			if fromStdin && fromFile != "" {
				return fmt.Errorf("--stdin and --from-file are mutually exclusive")
			}
			value, err := readSecretInput(fromStdin, fromFile)
			if err != nil {
				return err
			}
			defer zeroBytes(value)
			store, err := openStore()
			if err != nil {
				return err
			}
			return store.Set(args[0], string(value))
		},
	}
	set.Flags().BoolVar(&fromStdin, "stdin", false, "read the secret from stdin")
	set.Flags().StringVar(&fromFile, "from-file", "", "read the secret from a file")
	root.AddCommand(set)

	root.AddCommand(&cobra.Command{
		Use:   "list",
		Short: "List locally stored secret names",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			store, err := openStore()
			if err != nil {
				return err
			}
			keys, err := store.List()
			if err != nil {
				return err
			}
			sort.Strings(keys)
			for _, key := range keys {
				fmt.Fprintln(cmd.OutOrStdout(), key)
			}
			return nil
		},
	})

	root.AddCommand(&cobra.Command{
		Use:   "remove <key>",
		Short: "Remove a locally stored secret",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			store, err := openStore()
			if err != nil {
				return err
			}
			return store.Remove(args[0])
		},
	})
	return root
}

func readSecretInput(fromStdin bool, fromFile string) ([]byte, error) {
	if fromFile != "" {
		file, err := os.Open(fromFile)
		if err != nil {
			return nil, err
		}
		defer file.Close()
		return readLimitedSecret(file)
	}
	if fromStdin || !term.IsTerminal(int(os.Stdin.Fd())) {
		return readLimitedSecret(os.Stdin)
	}
	fmt.Fprint(os.Stderr, "Secret value: ")
	value, err := term.ReadPassword(int(os.Stdin.Fd()))
	fmt.Fprintln(os.Stderr)
	return value, err
}

func readLimitedSecret(reader io.Reader) ([]byte, error) {
	buffered := bufio.NewReader(io.LimitReader(reader, maxSecretBytes+1))
	value, err := io.ReadAll(buffered)
	if err != nil {
		return nil, err
	}
	if len(value) > maxSecretBytes {
		zeroBytes(value)
		return nil, fmt.Errorf("secret exceeds %d bytes", maxSecretBytes)
	}
	return value, nil
}

func zeroBytes(value []byte) {
	for index := range value {
		value[index] = 0
	}
}
